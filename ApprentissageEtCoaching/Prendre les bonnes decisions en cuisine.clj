Comment cuire les viandes/poissons : au four ou en grillade (pas beacoup de graisse)
quelle matiere grasse utiliser : 1-2 cuillere a cafe huile olive (eviter le beurre car acides gras saturés)
et eviter margarine. pour les oeufs, cuire les blancs et laisser les jaunes crus (oeuf poches coque ou plat)
Comment cuire les legumes : a la vapeur ou a letouffee (pour garder vitamines et mineraux)+1cc huile olive
la cuisson a l'eau est a eviter car perte vitamines et mineraux .. la cuisson au micro onde est a eviter aussi
preferer la cuisson a la vapeur et au four.
Pour les feculents pates et riz à l'eau bouillante salée (1 litre d'eau + 10g sel par 100g de pates ou riz)
evitez les plats qui demandent de repasser le riz à la poele.
Les pommes de terre : cuisson a l'eau ou au four (eviter friture)
Les salades : utiliser huile olive + vinaigre balsamique ou jus de citron
Les sauces : eviter sauces cremes et bechamel, preferer sauces tomates maison ou sauces a base de yaourt nature
