deconstruisez une de vos mauvaises habitudes
La boucle d'habitude est constituée 
- un declencheur
- une envie
- une action 
- une recompense
rappel : 40% de nos actions sont des habitudes 
cherchons une strategie personnelle qui va nous permettre de faire ladifference entre avoir faim et avoir envie de manger
prendre une feuille de papier, 
repenser a tous les moments tous les evenements qui ont donne envie de manger la semaine derniere
noter a cote de chaque evenement le declencheur, l envie, l action et la recompense
pour chaque evenement, essayer de trouver une alternative a l action qui pourrait donner la meme recompense
par exemple, si le declencheur est le stress, l envie est de se detendre, l action est de manger un gateau et la recompense est de se sentir mieux, une alternative pourrait etre de faire une courte promenade ou de pratiquer la meditation pour se detendre.
